
package com.nocam.security

import java.util.UUID

data class ScanFinding(
    val host: String,
    val port: Int,
    val service: String,
    val state: String,
    val detail: String,
    val severity: String = "INFO"
)

data class ScanReport(
    val scanId: String,
    val startedAt: String,
    val finishedAt: String,
    val scope: String,
    val findings: List<ScanFinding>,
    val notes: List<String>
) {
    val openCount: Int
        get() = findings.count { it.state == "OPEN" }

    val hostCount: Int
        get() = findings.map { it.host }.distinct().size

    fun toMarkdown(): String = buildString {
        appendLine("# NOCAM Security Assessment")
        appendLine()
        appendLine("- Scan ID: `$scanId`")
        appendLine("- Started: $startedAt")
        appendLine("- Finished: $finishedAt")
        appendLine("- Scope: `$scope`")
        appendLine("- Hosts assessed: $hostCount")
        appendLine("- Open TCP ports: $openCount")
        appendLine()
        appendLine("## Findings")
        appendLine()
        appendLine("| Host | Port | Service | State | Severity | Detail |")
        appendLine("|---|---:|---|---|---|---|")

        findings.forEach {
            appendLine(
                "| ${it.host} | ${it.port} | ${it.service} | " +
                    "${it.state} | ${it.severity} | " +
                    "${it.detail.replace("|", "/")} |"
            )
        }

        appendLine()
        appendLine("## Notes")
        notes.forEach { appendLine("- $it") }
        appendLine()
        appendLine(
            "Generated by NOCAM by Anonymous-beta. " +
                "An open port does not prove a vulnerability."
        )
    }
}

fun jsonEscape(value: String): String = buildString {
    value.forEach { ch ->
        when (ch) {
            '\\' -> append("\\\\")
            '"' -> append("\\\"")
            '\n' -> append("\\n")
            '\r' -> append("\\r")
            '\t' -> append("\\t")
            else -> {
                if (ch.code < 0x20) {
                    append("\\u%04x".format(ch.code))
                } else {
                    append(ch)
                }
            }
        }
    }
}

fun ScanReport.toJson(): String = buildString {
    appendLine("{")
    appendLine("  \"scanId\": \"${jsonEscape(scanId)}\",")
    appendLine("  \"startedAt\": \"${jsonEscape(startedAt)}\",")
    appendLine("  \"finishedAt\": \"${jsonEscape(finishedAt)}\",")
    appendLine("  \"scope\": \"${jsonEscape(scope)}\",")
    appendLine("  \"hostCount\": $hostCount,")
    appendLine("  \"openCount\": $openCount,")
    appendLine("  \"findings\": [")

    findings.forEachIndexed { index, finding ->
        append(
            "    {\"host\":\"${jsonEscape(finding.host)}\"," +
                "\"port\":${finding.port}," +
                "\"service\":\"${jsonEscape(finding.service)}\"," +
                "\"state\":\"${jsonEscape(finding.state)}\"," +
                "\"detail\":\"${jsonEscape(finding.detail)}\"," +
                "\"severity\":\"${jsonEscape(finding.severity)}\"}"
        )

        if (index != findings.lastIndex) append(',')
        appendLine()
    }

    appendLine("  ],")
    appendLine("  \"notes\": [")

    notes.forEachIndexed { index, note ->
        append("    \"${jsonEscape(note)}\"")
        if (index != notes.lastIndex) append(',')
        appendLine()
    }

    appendLine("  ]")
    appendLine("}")
}
